// Regenerates constants/country-names.ts — Hindi and Bengali country names for
// every ISO code the location picker lists (from the country-state-city package).
// Run: node scripts/gen-country-names.mjs
// Uses Node's full-ICU Intl.DisplayNames at build time only; the app never calls
// Intl.DisplayNames at runtime (Hermes support is not guaranteed).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { Country } = require('country-state-city');

const hi = new Intl.DisplayNames(['hi'], { type: 'region', fallback: 'none' });
const bn = new Intl.DisplayNames(['bn'], { type: 'region', fallback: 'none' });

const rows = [];
const missing = [];
for (const c of Country.getAllCountries().sort((a, b) => a.isoCode.localeCompare(b.isoCode))) {
  const h = hi.of(c.isoCode);
  const b = bn.of(c.isoCode);
  if (!h || !b) { missing.push(c.isoCode); continue; } // falls back to English at runtime
  rows.push(`  ${c.isoCode}: { hi: ${JSON.stringify(h.normalize('NFC'))}, bn: ${JSON.stringify(b.normalize('NFC'))} },`);
}

const out = `/**
 * Hindi and Bengali country names, keyed by ISO 3166-1 alpha-2 code.
 * GENERATED by scripts/gen-country-names.mjs (Node full-ICU Intl.DisplayNames,
 * type 'region') — do not edit by hand; re-run: node scripts/gen-country-names.mjs
 * Display only: stored places always use the English names from country-state-city.
 */
export const COUNTRY_NAMES: Record<string, { hi: string; bn: string }> = {
${rows.join('\n')}
};
`;
writeFileSync(fileURLToPath(new URL('../constants/country-names.ts', import.meta.url)), out);
console.log(`wrote ${rows.length} countries; missing: ${missing.join(',') || 'none'}`);
